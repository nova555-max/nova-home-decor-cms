export const dictionaries = { ku, ar, en } as const;

export type DictionaryKey = keyof typeof ku;

function getNestedValue(obj: unknown, key: string): string | undefined {
  const parts = key.split(".");
  let current: unknown = obj;
  for (const part of parts) {
    if (current == null || typeof current !== "object") return undefined;
    current = (current as Record<string, unknown>)[part];
  }
  return typeof current === "string" ? current : undefined;
}

export function t(
  locale: Locale,
  section: keyof typeof ku,
  key: string,
): string {
  const fullKey = `${String(section)}.${key}`;
  const cms = lookupCmsValue(getRequestContentOverrides(), fullKey, locale);
  if (cms) return cms;

  const dict = dictionaries[locale][section];
  const fallback = dictionaries.ku[section];
  return (
    getNestedValue(dict, key) ??
    getNestedValue(fallback, key) ??
    key
  );
}

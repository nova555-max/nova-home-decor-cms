export const dashboardDictionaries = { ku, ar, en } as const;

function getNested(
  obj: Record<string, unknown>,
  path: string,
): string | undefined {
  const parts = path.split(".");
  let current: unknown = obj;
  for (const part of parts) {
    if (current == null || typeof current !== "object") return undefined;
    current = (current as Record<string, unknown>)[part];
  }
  return typeof current === "string" ? current : undefined;
}

export function td(locale: Locale, key: string): string {
  const dict = dashboardDictionaries[locale] as Record<string, unknown>;
  const fallback = dashboardDictionaries.ku as Record<string, unknown>;
  return getNested(dict, key) ?? getNested(fallback, key) ?? key;
}
